// Regenerate src/ui/fonts.generated.ts from the pinned Google Fonts files.
//
//   bun scripts/fonts.ts
//
// The Worker serves these bytes itself under /v/assets/ so that a share
// recipient's browser never contacts a third party. Both families are licensed
// under the SIL Open Font License 1.1, which permits bundling.
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";

const SOURCES = [
  {
    stem: "bricolage-grotesque",
    sha256: "85f55a58a31e61a2e19e8bb25fed503181bf2a6b4cab76c589992cfaac377447",
    url: "https://fonts.gstatic.com/s/bricolagegrotesque/v9/3y9K6as8bTXq_nANBjzKo3IeZx8z6up5BeSl9D4dj_x9PpZBMlGIInHWVyNJ.woff2",
  },
  {
    stem: "hanken-grotesk",
    sha256: "1f21c6eaa0000f3329cfcfac966b43d5bebf5aa610303e33294ac31bc6f4bb59",
    url: "https://fonts.gstatic.com/s/hankengrotesk/v12/ieVn2YZDLWuGJpnzaiwFXS9tYtpd59CxCis4.woff2",
  },
  {
    stem: "hanken-grotesk-italic",
    sha256: "99721f51a4d5925d9d08021fb5575ef017fa18a40578ca897485808ce68bc19a",
    url: "https://fonts.gstatic.com/s/hankengrotesk/v12/ieVl2YZDLWuGJpnzaiwFXS9tYtpY19K7DQk6YvM.woff2",
  },
];

const entries: string[] = [];
const names: string[] = [];
for (const { stem, sha256, url } of SOURCES) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  // Pinned so a changed upstream file fails here instead of shipping silently.
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== sha256) throw new Error(`${url}: sha256 ${digest}, expected ${sha256}`);
  // A content hash in the name lets the route cache each file forever.
  const name = `${stem}-${digest.slice(0, 10)}.woff2`;
  names.push(`  ${JSON.stringify(stem)}: ${JSON.stringify(name)},`);
  entries.push(`  [${JSON.stringify(name)}, ${JSON.stringify(bytes.toString("base64"))}],`);
}

await writeFile(
  new URL("../src/ui/fonts.generated.ts", import.meta.url),
  `// Generated by scripts/fonts.ts. Do not edit.
// Bricolage Grotesque and Hanken Grotesk, latin subsets, SIL Open Font License 1.1.

export const FONT_FILES = {
${names.join("\n")}
} as const;

export const FONT_DATA: ReadonlyMap<string, string> = new Map([
${entries.join("\n")}
]);
`,
);
